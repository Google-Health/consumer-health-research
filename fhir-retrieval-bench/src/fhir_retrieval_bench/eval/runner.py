def json_default(o):
  if isinstance(o, datetime.timedelta):
    return o.total_seconds()
  raise TypeError(repr(o) + " is not JSON serializable")


@dataclasses.dataclass
class EvalResult:
  """The result of processing and judging a single patient record.

  Attributes:
    instance_id: The unique identifier for the evaluation instance.
    patient_id: The identifier for the patient.
    question: The original question asked about the patient's record.
    question_for_answering: The question asked to the model for answering.
    ground_truth: The expected correct answer.
    source_meta: Metadata about the source of the instance.
    bundle_preview: A preview/summary of the FHIR bundle used.
    strategy: The name of the strategy used for retrieval and answer generation.
    model: The name of the language model used for answering.
    run_success: True if the strategy execution was successful.
    run_error: Error message if the strategy execution failed, otherwise None.
    prompt_preview: A preview of the prompt sent to the model.
    prediction: The answer generated by the model.
    run_extra_data: Additional data from the strategy execution.
    judge_success: True if the judging process was successful, None if not
      judged.
    judge_error: Error message if judging failed, otherwise None.
    is_correct: True if the prediction was judged correct, False if incorrect,
      None if judging failed or wasn't performed.
    eval_reason: Explanation from the judge for the correctness evaluation.
    execution_time: Total time taken to process the instance.
    context_token_count: The number of tokens in the context provided to the
      model.
    context_window_limit: The maximum token limit of the model's context window.
    context_fit_pct: The percentage of the context window used, or None if not
      applicable.
  """
  # Instance metadata
  instance_id: str
  patient_id: str
  question: str
  question_for_answering: str
  ground_truth: str
  source_meta: dict[str, Any]
  bundle_preview: str
  # Config details
  strategy: str
  model: str
  # Prediction details
  run_success: bool
  run_error: str | None
  prompt_preview: str
  prediction: str | None
  run_extra_data: dict[str, Any] | None
  # Judgement details
  judge_success: bool | None
  judge_error: str | None
  is_correct: bool | None
  eval_reason: str | None
  # Runtime & resource details
  execution_time: datetime.timedelta
  context_token_count: int
  context_window_limit: int
  context_fit_pct: float | None


@dataclasses.dataclass
class EvalMetrics:
  """Headline metrics computed across all processed records."""
  total_rows: int
  total_rows_valid: int
  non_error_count: int
  token_errors: int
  errored_rows: int
  correct: int
  correct_all_rows: int
  correct_non_error: int
  accuracy: float
  accuracy_all_rows: float
  accuracy_excluding_errors: float
  avg_tokens: float
  avg_context_tokens: float
  context_fit_pct: float
  context_window_limit: int

  def __str__(self) -> str:
    """Provides a clean, human-readable summary for logging."""
    return (
        f"accuracy(v2)={self.accuracy * 100:.2f}% "
        f"({self.correct}/{self.total_rows_valid} valid) | "
        f"accuracy_all_rows={self.accuracy_all_rows * 100:.2f}% "
        f"({self.correct_all_rows}/{self.total_rows}) | "
        f"excl_pipeline_errors={self.accuracy_excluding_errors * 100:.2f}% "
        f"({self.correct_non_error}/{self.non_error_count}) | "
        f"token_errors={self.token_errors} | errors={self.errored_rows} | "
        f"ctx_window={self.context_window_limit}"
    )


def _run_id(experiment_config: config.ExperimentConfig) -> str:
  """Generate a unique run ID based on the experiment configuration."""
  answer_model = "".join(
      ch if ch.isalnum() or ch in ("-", "_", ".") else "_"
      for ch in experiment_config.models.answer.model
  ).strip("._")
  payload = {
      "dataset": experiment_config.dataset.model_dump(),
      "strategy": experiment_config.strategy.model_dump(),
      "models": experiment_config.models.model_dump(),
  }
  encoded = json.dumps(payload, sort_keys=True, separators=(",", ":"))
  fingerprint = hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:6]

  return (
      f"{experiment_config.dataset.name}"
      f"_{experiment_config.strategy.name}"
      f"_{answer_model}"
      f"_{fingerprint}"
  )


def _checkpoint_path(
    output_dir: str, experiment_config: config.ExperimentConfig
) -> str:
  return os.path.join(
      output_dir, f".checkpoint_{_run_id(experiment_config)}.jsonl"
  )


def _load_checkpoint(path: str) -> list[EvalResult]:
  """Load evaluation results from a checkpoint file."""
  results = []
  try:
    with open(path, "r") as f:
      for lineno, line in enumerate(f, 1):
        line = line.strip()
        if not line:
          continue
        try:
          data = json.loads(line)
          results.append(EvalResult(**data))
        except (json.JSONDecodeError, TypeError) as e:
          logging.warning(
              "Skipping malformed line %d in %s: %s", lineno, path, e
          )
  except OSError:
    # File does not exist or other OS error, treat as no checkpoint.
    return []
  return results


def _compute_metrics_for_all(results: Collection[EvalResult]) -> dict[str, Any]:
  valid_results = [r for r in results if r.run_success]
  valid_results_with_judge_success = [
      r for r in valid_results if r.judge_success
  ]
  accuracy = np.mean([r.is_correct for r in valid_results_with_judge_success])

  avg_tokens = np.mean([r.context_token_count for r in results])
  avg_context_window_limit = np.mean([r.context_window_limit for r in results])

  return {
      "tried_instances": len(results),
      "ran_instances": len(valid_results),
      "accuracy": accuracy,
      "avg_tokens": avg_tokens,
      "avg_context_window_limit": avg_context_window_limit,
  }


def _dataset_signature(total_records: int, head: list[tuple[str, str]]) -> str:
  payload = f"n={total_records};"
  payload += ";".join(
      f"{patient_id}:{question}" for patient_id, question in head
  )
  return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:8]


def process_single_record(
    instance: data_base.EvalInstance,
    bundles: dict[str, dict[str, Any]],
    experiment_config: config.ExperimentConfig,
    creds: api.Credentials,
    output_dir: pathlib.Path | None = None,
    cache_dir: pathlib.Path | None = None,
) -> EvalResult:
  """Process one record end-to-end: run strategy then judge the prediction.

  Args:
    instance: The evaluation instance containing patient/question data.
    bundles: A dictionary of FHIR bundles keyed by patient ID.
    experiment_config: The configuration for the current experiment.
    creds: API credentials.
    output_dir: Directory for experiment outputs.
    cache_dir: Directory for caching.

  Returns:
    An EvalResult dataclass instance containing the results of the strategy
    execution and the judging process, including success status, any errors,
    the prediction, and performance metrics.
  """
  logging.debug(
      "Processing instance_id=%s | patient_id=%s | question=%r...",
      instance.instance_id,
      instance.patient_id,
      instance.question[:80],
  )
  bundle = loader.get_fhir_bundle_for_instance(instance, bundles)
  if bundle is None:
    raise ValueError(
        f"No FHIR bundle found for patient {instance.patient_id}"
    )
  bundle_preview = str({
      k: str(v) if len(str(v)) < 100 else (str(v)[:100] + "...")
      for k, v in bundle.items()
  })
  start_time = time.time()

  strategy = strategy_registry.get_strategy(
      strategy_config=experiment_config.strategy,
      model_config=experiment_config.models,
      creds=creds,
      dataset_name=experiment_config.dataset.name,
      output_dir=output_dir,
      cache_dir=cache_dir
  )
  prediction, run_extra_data, run_error, _, prompt, prompt_token_count = (
      strategy.process(instance, bundle)
  )
  prompt_preview = prompt[:1000] + "..." if len(prompt) > 1000 else prompt
  if prediction is None:
    return EvalResult(
        # Instance metadata
        instance_id=instance.instance_id,
        patient_id=instance.patient_id,
        question=instance.question,
        question_for_answering=instance.question_for_answering,
        ground_truth=instance.ground_truth,
        source_meta=instance.source_meta,
        bundle_preview=bundle_preview,
        # Config details
        strategy=experiment_config.strategy.name,
        model=experiment_config.models.answer.model,
        # Prediction details
        run_success=False,
        run_error=run_error,
        prompt_preview=prompt_preview,
        prediction=prediction,
        run_extra_data=run_extra_data,
        # Judgement details
        judge_success=None,
        judge_error=None,
        is_correct=None,
        eval_reason=None,
        # Runtime & resource details
        execution_time=datetime.timedelta(seconds=time.time() - start_time),
        context_token_count=prompt_token_count,
        context_window_limit=strategy.context_window_limit,
        context_fit_pct=None,
    )

  strategy_elapsed = time.time() - start_time
  logging.debug(
      "Strategy done for patient=%s in %.2fs | prediction_len=%d",
      instance.patient_id,
      strategy_elapsed,
      len(prediction),
  )

  judge_start = time.time()
  is_correct, eval_reason = judge.evaluate_answer(
      instance.question_for_answering,
      instance.ground_truth,
      prediction,
      experiment_config,
      creds,
  )

  judge_success = is_correct is not None
  judge_error = None
  if not judge_success:
    judge_error = f"Judge failed to produce a and answer. Reason: {eval_reason}"
    logging.warning(
        "Judge failed for instance_id=%s | Reason: %s",
        instance.instance_id, eval_reason
    )

  judge_elapsed = time.time() - judge_start
  total_elapsed = time.time() - start_time

  logging.debug(
      "Judged instance_id=%s | is_correct=%s | eval_reason=%s | "
      "judge_time=%.2fs | total_time=%.2fs",
      instance.instance_id,
      is_correct,
      eval_reason,
      judge_elapsed,
      total_elapsed,
  )

  return EvalResult(
      # Instance metadata
      instance_id=instance.instance_id,
      patient_id=instance.patient_id,
      question=instance.question,
      question_for_answering=instance.question_for_answering,
      ground_truth=instance.ground_truth,
      source_meta=instance.source_meta,
      bundle_preview=bundle_preview,
      # Config details
      strategy=experiment_config.strategy.name,
      model=experiment_config.models.answer.model,
      # Prediction details
      run_success=True,
      run_error=None,
      prompt_preview=prompt_preview,
      prediction=prediction,
      run_extra_data=run_extra_data,
      # Judgement details
      judge_success=judge_success,
      judge_error=judge_error,
      is_correct=is_correct,
      eval_reason=eval_reason,
      # Runtime & resource details
      execution_time=datetime.timedelta(seconds=total_elapsed),
      context_token_count=prompt_token_count,
      context_window_limit=strategy.context_window_limit,
      context_fit_pct=(prompt_token_count / strategy.context_window_limit),
  )


def run_experiment(
    experiment_config: config.ExperimentConfig,
    creds: api.Credentials,
    shuffle: bool = False,
    max_rows: int | None = None,
    num_workers: int = 10,
    output_dir: pathlib.Path | None = None,
    cache_dir: pathlib.Path | None = None,
) -> dict[str, Any]:
  """Run a full evaluation: load data, process each record, judge, save, and upload."""

  logging.info(
      "run_experiment starting | dataset=%s strategy=%s answer_model=%s "
      "judge_model=%s shuffle=%s max_rows=%s num_workers=%d",
      experiment_config.dataset.name,
      experiment_config.strategy.name,
      experiment_config.models.answer.model,
      experiment_config.models.judge.model,
      shuffle,
      max_rows,
      num_workers,
  )
  experiment_output_dir = pathlib.Path(output_dir) / _run_id(experiment_config)

  if not os.path.exists(experiment_output_dir):
    os.makedirs(experiment_output_dir)

  # Save/verify config.yaml
  config_path = experiment_output_dir / "config.yaml"
  existing_config_dict = None
  try:
    with open(str(config_path), "rt") as f:
      existing_config_dict = yaml.safe_load(f)
  except OSError:
    # Config file doesn't exist, will write a new one.
    pass

  if existing_config_dict:
    if existing_config_dict != experiment_config.model_dump():
      raise ValueError(
          f"Existing config in {config_path} is not identical to the current "
          "config. Resuming is only allowed with the same configuration."
      )
    logging.info("Resuming benchmark with identical configuration.")
  else:
    with open(str(config_path), "w") as f:
      yaml.dump(experiment_config.model_dump(), f)
    logging.info("Saved configuration to %s", config_path)

  eval_start = time.time()

  instances = loader.load_qa_pairs(
      experiment_config.dataset, shuffle=shuffle, limit=max_rows
  )

  logging.info(
      "Prepared dataset for %s | total_count=%d",
      experiment_config.dataset.name,
      len(instances),
  )

  # --- Checkpoint Recovery ---
  ckpt_path = os.path.join(experiment_output_dir, "checkpoint.jsonl")
  checkpoint_results_by_instance_id_all = defaultdict(list)
  for r in _load_checkpoint(ckpt_path):
    checkpoint_results_by_instance_id_all[r.instance_id].append(r)
  checkpoint_results_by_instance_id = {}
  for instance_id, results in checkpoint_results_by_instance_id_all.items():
    for r in results:
      if r.run_success:
        checkpoint_results_by_instance_id[instance_id] = r
        break  
  # checkpoint_results_by_instance_id = {
  #     r.instance_id: r for r in _load_checkpoint(ckpt_path)
  # }

  pending_instances: list[data_base.EvalInstance] = []
  results: list[EvalResult] = []
  pbar = tqdm.tqdm(total=len(instances), desc="Processing Instances")

  # 1. Filter out already completed records ()
  for instance in instances:
    if instance.instance_id in checkpoint_results_by_instance_id:
      results.append(checkpoint_results_by_instance_id[instance.instance_id])
      logging.info(
          "Loaded checkpoint for instance_id=%s | patient_id=%s",
          instance.instance_id,
          instance.patient_id,
      )
      pbar.update(1)
    else:
      pending_instances.append(instance)

  # 2. Execute pending records natively
  if pending_instances:
    logging.info(
        "Launching ThreadPoolExecutor for %d pending records",
        len(pending_instances),
    )
    bundles = loader.load_fhir_bundles(experiment_config.dataset)
    logging.info("Loaded %d FHIR bundles", len(bundles))
    if num_workers == 1:
      for instance in pending_instances:
        result_obj: EvalResult = process_single_record(
            instance,
            bundles,
            experiment_config,
            creds.shuffled(),
            experiment_output_dir,
            cache_dir,
        )
        results.append(result_obj)
        with open(ckpt_path, "a") as pf:
          pf.write(
              json.dumps(dataclasses.asdict(result_obj), default=json_default)
              + "\n"
          )
        pbar.update(1)
    elif num_workers > 1:
      with concurrent.futures.ThreadPoolExecutor(
          max_workers=num_workers
      ) as executor:
        future_to_record = {
            executor.submit(
                process_single_record,
                instance,
                bundles,
                experiment_config,
                creds.shuffled(),
                experiment_output_dir,
                cache_dir,
            ): instance
            for instance in pending_instances
        }
        for future in concurrent.futures.as_completed(future_to_record):
          instance = future_to_record[future]
          try:
            result_obj: EvalResult = future.result()
            results.append(result_obj)
            with open(ckpt_path, "a") as pf:
              pf.write(
                  json.dumps(
                      dataclasses.asdict(result_obj), default=json_default
                  )
                  + "\n"
              )
          except Exception as e:  # pylint: disable=broad-except
            logging.exception(
                "Exception encountered while processing instance_id=%s |"
                " patient_id=%s: %s",
                instance.instance_id,
                instance.patient_id,
                e,
            )
          finally:
            pbar.update(1)

  pbar.close()

  # ---------- METRICS & SUMMARIES ----------

  eval_elapsed = time.time() - eval_start
  metrics = _compute_metrics_for_all(results)

  print(f"\n{'=' * 50}")
  print("Benchmark Summary")
  print(f"Total time: {eval_elapsed:.2f}s")
  print(metrics)
  print(f"{'=' * 50}\n")

  # ---------- SAVE RESULTS ----------
  results_file = experiment_output_dir / "results.json"
  with open(results_file, "w") as f:
    json.dump(
        [dataclasses.asdict(r) for r in results],
        f,
        indent=2,
        default=json_default,
    )
  logging.info("Results saved to %s", results_file)

  # ---------- SAVE SUMMARY ----------
  summary_file = experiment_output_dir / "summary.json"
  with open(summary_file, "w") as f:
    json.dump(metrics, f, indent=2)
  logging.info("Summary saved to %s", summary_file)

  return metrics
