"""Core evaluation runner.

Loads data, runs a strategy on each record, judges the result,
and saves/uploads results.

Supports crash recovery: per-record results are streamed to a JSONL
checkpoint file as they complete. On restart, already-completed records
are skipped automatically.
"""

