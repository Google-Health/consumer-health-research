_FORMULA_SYMBOLS: Dict[str, str] = {**ATOM_SYMBOLS, 'DL': 'd'}


def _atom_symbol(atom: str, symbols: Mapping[str, str]) -> str:
  r"""LaTeX of one variable name; unknown names verbatim in ``\text{}``."""
  symbol = symbols.get(atom)
  if symbol is None:
    symbol = r'\text{' + atom.replace('_', r'\_') + '}'
  return symbol


def _formula_to_latex(formula: str) -> str:
  r"""Strips the LHS of a patsy formula and rewrites the RHS in table notation.

  The right-hand side is tokenised into variable names and operators; every
  name is mapped as a whole (``ATOM_SYMBOLS``, unknown names escaped in
  ``\text{}``), ``*`` and ``:`` become ``\cdot``.

  Args:
    formula: Full patsy formula, e.g. ``'y ~ age_c + month_sin'``.

  Returns:
    The right-hand side in the notation used in the tables.
  """
  rhs = re.sub(r'^[^~]*~\s*', '', formula)
  pieces: List[str] = []
  for token in _FORMULA_TOKEN_RE.findall(rhs):
    if token in ('*', ':'):
      pieces.append(r' \cdot ')
    elif token == '+':
      pieces.append(' + ')
    elif token[0].isalpha() or token[0] == '_':
      pieces.append(_atom_symbol(token, _FORMULA_SYMBOLS))
    else:
      pieces.append(token)
  return ''.join(pieces)


def term_symbol(term: str) -> str:
  r"""LaTeX math of a patsy term (unknown atoms verbatim in ``\text{}``)."""
  return r' \cdot '.join(
      _atom_symbol(atom, ATOM_SYMBOLS) for atom in term.split(':')
  )


def term_label(term: str) -> str:
  r"""Indented row label ``\quad \(symbol\)`` of a fixed-effect term."""
  return f'\\quad \\({term_symbol(term)}\\)'


def term_group(term: str) -> str:
  """Predictor family of a term per ``_TERM_GROUP_RULES``, else 'Other'."""
  for needle, group in _TERM_GROUP_RULES:
    if needle in term:
      return group
  return _OTHER_GROUP


def _harmonic_pair(
    term: str,
) -> Optional[Tuple[str, str, int, str]]:
  """(sin_term, cos_term, period, label) of a one-harmonic term, else None."""
  atoms = term.split(':')
  for sin_atom, cos_atom, period, symbol in _HARMONIC_PAIRS:
    hits = [a for a in atoms if a in (sin_atom, cos_atom)]
    if len(hits) != 1:
      continue
    sin_term = ':'.join(sin_atom if a == hits[0] else a for a in atoms)
    cos_term = ':'.join(cos_atom if a == hits[0] else a for a in atoms)
    symbols = [term_symbol(a) for a in atoms if a != hits[0]] + [symbol]
    label = '\\quad \\(' + r' \cdot '.join(symbols) + '\\)'
    return sin_term, cos_term, period, label
  return None


def fixed_effect_terms(rows: Sequence[Row]) -> List[str]:
  """Fixed-effect terms (not variance components) with any estimate in rows."""
  prefix = 'beta_std_'
  terms: List[str] = []
  for row in rows:
    for col in row:
      if not col.startswith(prefix) or col.endswith(' Var'):
        continue
      term = col[len(prefix) :]
      if term not in terms and _get_float(row, col) is not None:
        terms.append(term)
  return terms


def _warn_extra_terms(terms: Sequence[str], table: str) -> None:
  if terms:
    warnings.warn(
        f'{table}: terms outside the predefined row layout were added with'
        f' generic labels: {list(terms)}',
        stacklevel=3,
    )


