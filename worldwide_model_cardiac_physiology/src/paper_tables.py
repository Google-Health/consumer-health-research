def _records(results_df: pd.DataFrame) -> List[Row]:
  return [dict(r) for r in results_df.to_dict('records')]


def select_stage_winners(
    results_df: pd.DataFrame, winners: Mapping[int, str]
) -> dict[int, Row]:
  """Maps stage -> first CSV row whose ``model`` equals the winner's name.

  Args:
    results_df: Rows of ``lme-models-results-{metric}.csv`` (needs the ``model``
      column).
    winners: Table stage -> winning ``model`` name, normally the output of
      :func:`infer_stage_winners`.

  Returns:
    Dict mapping each stage in ``winners`` to the first matching row as a
    column -> value dict.

  Raises:
    KeyError: if a winner is not present in ``results_df``.
  """
  rows = _records(results_df)
  out: Dict[int, Row] = {}
  for stage, model_name in winners.items():
    match = [r for r in rows if r.get('model') == model_name]
    if not match:
      raise KeyError(
          f'Winner {model_name!r} (stage {stage}) not in results CSV'
      )
    out[stage] = match[0]
  return out


# Table stage -> prefix of the pipeline model names of its decision point.
# Pipeline stage 3 (season x day-length interactions) is diagnostic: nothing
# is carried forward, so it has no table column; its candidates are listed
# with the season candidates (table stage 2) in the candidate grid.
STAGE_MODEL_PREFIXES: Dict[int, str] = {
    1: 'Stage1_',
    2: 'Stage2_',
    3: 'Stage4_',
    4: 'Stage5_',
    5: 'Stage6_',
}
_TABLE_STAGE_BY_PREFIX: Tuple[Tuple[str, int], ...] = (
    ('Stage1_', 1),
    ('Stage2_', 2),
    ('Stage3_', 2),
    ('Stage4_', 3),
    ('Stage5_', 4),
    ('Stage6_', 5),
)


def table_stage_of_model(model: str) -> Optional[int]:
  """Table stage (1-5) a pipeline model name belongs to; None if unknown."""
  for prefix, stage in _TABLE_STAGE_BY_PREFIX:
    if model.startswith(prefix):
      return stage
  return None


def infer_stage_winners(results_df: pd.DataFrame) -> Dict[int, str]:
  """Derives the five table stage winners from the model-results CSV.

  For each table stage the row whose ``model`` starts with the corresponding
  pipeline prefix (``STAGE_MODEL_PREFIXES``) and that *progressed* to the next
  stage is taken (last ``progressed`` row of the stage, so an interacted
  Stage 4/5 model supersedes its main-effects base). Results CSVs written
  before ``stage_competition`` have no ``progressed`` column; there the
  lowest-BIC row of the stage is used, which is equivalent when no
  ``STAGE_OVERRIDES`` were applied. Every table function uses this when no
  ``winners`` mapping is passed.

  Args:
    results_df: Rows of ``lme-models-results-{metric}.csv``; needs the ``model``
      column and uses ``BIC`` and ``progressed`` when present.

  Returns:
    Dict mapping table stage (1-5) -> winning ``model`` name.

  Raises:
    KeyError: if a stage has no rows in ``results_df``.
  """
  winners: Dict[int, str] = {}
  has_flag = 'progressed' in results_df.columns
  for stage, prefix in STAGE_MODEL_PREFIXES.items():
    rows = results_df[results_df['model'].astype(str).str.startswith(prefix)]
    if rows.empty:
      raise KeyError(
          f'No model with prefix {prefix!r} (table stage {stage}) in'
          ' results CSV'
      )
    if has_flag:
      flagged = rows[rows['progressed'].astype(bool)]
      if not flagged.empty:
        winners[stage] = str(flagged['model'].iloc[-1])
        continue
    if 'BIC' in rows.columns:
      bic = pd.to_numeric(rows['BIC'], errors='coerce')
    else:
      bic = pd.Series(np.nan, index=rows.index)
    if bic.notna().any():
      winners[stage] = str(rows.loc[bic.idxmin(), 'model'])
    else:  # No usable BIC: keep the last candidate of the stage.
      winners[stage] = str(rows['model'].iloc[-1])
  return winners


def _unique_rows(results_df: pd.DataFrame) -> List[Row]:
  """Rows de-duplicated on ``model`` (first occurrence wins)."""
  seen = set()
  out: List[Row] = []
  for r in _records(results_df):
    name = r.get('model')
    if name in seen:
      continue
    seen.add(name)
    out.append(r)
  return out


