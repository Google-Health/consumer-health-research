def _demographic_stats(sub: pd.DataFrame, is_hrv: bool) -> Dict[str, str]:
  """Formatted cells of one (section, band) column of the demographics table.

  Cells: n = distinct users; age mean +- sd; user-months median [Q1, Q3]
  (truncated to int) and total; physiological value as mean +- sd (RHR) or a
  stacked median / [IQR] cell (HRV) of the per-user means. Empty subsets yield
  placeholder cells (``'0'``, ``'--'``, ``'0 [0, 0]'``).

  Args:
    sub: Per-user summary rows of one (section, band) cell, with columns
      ``user_id``, ``age``, ``months_contributed`` and ``val`` (the user's
      longitudinal mean RHR in bpm or HRV in ms).
    is_hrv: True for the HRV cohort (median [IQR] cell for ``val``); False for
      RHR (mean +- sd).

  Returns:
    Dict with the LaTeX-formatted cells keyed ``'n'``, ``'age'``,
    ``'months'``, ``'months_total'`` and ``'val'``.
  """
  if sub.empty:
    return {
        'n': '0',
        'age': '--',
        'months': '0 [0, 0]',
        'months_total': '0',
        'val': '--',
    }
  months = sub['months_contributed']
  cells = {
      'n': f"{int(sub['user_id'].nunique()):,}",
      'age': f"{sub['age'].mean():.1f} \\(\\pm\\) {sub['age'].std():.1f}",
      'months': (
          f'{int(months.median())} [{int(months.quantile(0.25))}, '
          f'{int(months.quantile(0.75))}]'
      ),
      'months_total': f'{int(months.sum()):,}',
  }
  val = sub['val']
  if is_hrv:
    med, q25, q75 = val.median(), val.quantile(0.25), val.quantile(0.75)
    cells['val'] = (
        f'\\begin{{tabular}}[t]{{@{{}}c@{{}}}}{med:.1f} \\\\ '
        f'{{[{q25:.1f}, {q75:.1f}]}}\\end{{tabular}}'
    )
  else:
    cells['val'] = f'{val.mean():.1f} \\(\\pm\\) {val.std():.1f}'
  return cells


