def _parameter_specs_with_extras(
    rows: Sequence[Row], table: str
) -> List[_ParamRowSpec]:
  """Layout specs plus a generic row per winner term outside the layout."""
  specs = parameter_table_specs()
  covered: set[str] = set()
  for spec in specs:
    covered.update((spec.single,) if spec.single else spec.paired or ())
  extra = [t for t in fixed_effect_terms(rows) if t not in covered]
  _warn_extra_terms(extra, table)
  specs.extend(
      _ParamRowSpec(term_label(t), _PARAM_GROUP_IDS[term_group(t)], single=t)
      for t in extra
  )
  order = list(_PARAM_GROUP_NAMES)
  return sorted(specs, key=lambda spec: order.index(spec.group))


# Raw-unit rescaling of the unstandardised estimates: latitude is stored in
# 1e-7 degrees (``lat_e7``), so per-unit coefficients are multiplied by 1e7
# (1e14 for the square) to read per degree (per degree squared).
_RAW_UNIT_SCALE: Dict[str, float] = {
    'lat_e7_c': 1e7,
    'abs_lat_e7_c': 1e7,
    'lat_e7_sq_c': 1e14,
}


def _raw_unit_scale(var: str) -> float:
  """Product of ``_RAW_UNIT_SCALE`` over the ``:``-separated atoms of a term."""
  scale = 1.0
  for atom in var.split(':'):
    scale *= _RAW_UNIT_SCALE.get(atom, 1.0)
  return scale


def _param_cell(
    row: Row, var: str, is_hrv: bool, standardised: bool
) -> Optional[str]:
  r"""``est & [lo, hi]`` cell pair; None if ``beta_std_{var}`` is missing.

  Significance is always judged on the standardised CI (inclusive rule
  ``lo <= 0 <= hi``); non-significant cells are bolded. Missing estimates or
  confidence bounds print as ``--``. Unstandardised latitude terms are
  rescaled to degrees (``_RAW_UNIT_SCALE``).

  Args:
    row: One results-CSV row (a fitted model) as a column -> value dict.
    var: Fixed-effect term name, e.g. ``'month_sin:lat_e7_c'``; the
      ``beta_{std,raw}_{var}`` / ``ci_{low,high}_{std,raw}_{var}`` columns are
      read.
    is_hrv: True for the HRV cohort: the log-scale estimate and CI are
      back-transformed to percentage change (``(exp(b) - 1) * 100``), or to the
      geometric mean (``exp(b)``) for the intercept.
    standardised: True to show ``beta_std_*`` with its CI; False to show
      ``beta_raw_*`` with the raw CI.

  Returns:
    LaTeX fragment ``'{est:.2f} & [{lo:.2f}, {hi:.2f}]'`` (both parts
    wrapped in ``\textbf`` when not significant), or None if the term is
    absent from ``row``.
  """
  std = _coef_ci(row, 'std', var)
  if std is None:
    return None
  _, std_lo, std_hi = std
  if standardised:
    beta, lo, hi = std
  else:
    scale = _raw_unit_scale(var)
    beta = _float_or_nan(row, f'beta_raw_{var}') * scale
    lo = _float_or_nan(row, f'ci_low_raw_{var}') * scale
    hi = _float_or_nan(row, f'ci_high_raw_{var}') * scale

  def trans(v: float) -> float:
    if not is_hrv:
      return v
    return math.exp(v) if var == 'Intercept' else _pct(v)

  est_str = '--' if math.isnan(beta) else f'{trans(beta):.2f}'
  ci_str = _fmt_ci(trans(lo), trans(hi))
  is_ns = var != 'Intercept' and (
      (std_lo <= 0 <= std_hi) or (std_hi <= 0 <= std_lo)
  )
  if is_ns:
    return f'\\textbf{{{est_str}}} & \\textbf{{{ci_str}}}'
  return f'{est_str} & {ci_str}'


def _param_spec_cell(
    row: Row, spec: _ParamRowSpec, is_hrv: bool, standardised: bool
) -> Optional[str]:
  if spec.single is not None:
    return _param_cell(row, spec.single, is_hrv, standardised)
  assert spec.paired is not None
  raw_var, res_var = spec.paired
  cell = _param_cell(row, raw_var, is_hrv, standardised)
  if cell is None:
    cell = _param_cell(row, res_var, is_hrv, standardised)
  return cell


