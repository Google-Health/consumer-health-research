def _parameter_table(
    results_df: pd.DataFrame,
    metric: str,
    standardised: bool,
    winners: Optional[Dict[int, str]],
    caption: Optional[str],
    label: Optional[str],
    log_likelihood_is_negated: bool,
    include_fit_diagnostics: bool,
    font_cmd: Optional[str],
    out_dir: Optional[str],
) -> str:
  """Shared renderer of the (un)standardised 11-column parameter tables."""
  is_hrv = _is_hrv(metric)
  winners = winners or infer_stage_winners(results_df)
  kind = 'standardised' if standardised else 'unstandardised'
  label = label or f'tab:supp_results_{metric}_{kind}'
  if caption is None:
    what = (
        'Full Standardised Fixed-Effects Trajectories'
        if standardised
        else 'Full Unstandardised Fixed-Effects Parameter Estimates'
    )
    caption = (
        f'{what}, Variance Components, and Model Fit Diagnostics for '
        f'Longitudinal {METRIC_LONG_NAME[metric]} Models across Progressive '
        'Hierarchical Stages.'
    )
  font_cmd = font_cmd or _PARAM_FONT_CMD[metric]
  stage_rows = select_stage_winners(results_df, winners)
  rows = [stage_rows[s] for s in STAGES]
  unit = r'[\%]' if is_hrv else '[bpm]'
  blank = ' & ' * 10 + r'\\'

  if standardised:
    col_hdr = (
        f'\\textbf{{Std. \\(\\beta\\) {unit}}} & \\textbf{{Std. CI {unit}}}'
    )
  else:
    col_hdr = f'\\textbf{{Est. {unit}}} & \\textbf{{95\\% CI {unit}}}'
  stage_hdr = ' & '.join(
      f'\\multicolumn{{2}}{{c}}{{\\textbf{{Stage {s} Winner}}}}' for s in STAGES
  )

  out = [
      r'\begin{sidewaystable}[htbp]',
      r'    \centering',
      f'    {font_cmd}',
      r'    \begin{threeparttable}',
      f'    \\caption{{\\textbf{{{caption}}}}}',
      f'    \\label{{{label}}}',
      r'    \setlength{\tabcolsep}{1.0pt}',
      r'    \begin{tabular}{l cc cc cc cc cc}',
      r'        \toprule',
      f'         & {stage_hdr} \\\\',
      r'        \cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7} '
      + r'\cmidrule(lr){8-9} \cmidrule(lr){10-11}',
      r'        \textbf{Predictors} & '
      + ' & '.join([col_hdr] * len(STAGES))
      + ' \\\\',
      r'        \midrule',
      f'        \\textbf{{Fixed Effects: {_PARAM_GROUP_NAMES[1]}}} {blank}',
  ]

  cur_group = 1
  for spec in _parameter_specs_with_extras(rows, f'{kind}_parameter_table'):
    cells = [_param_spec_cell(r, spec, is_hrv, standardised) for r in rows]
    if all(c is None for c in cells):
      continue
    if spec.group != cur_group:
      cur_group = spec.group
      out.append(r'        \midrule')
      out.append(
          f'        \\textbf{{Fixed Effects: {_PARAM_GROUP_NAMES[cur_group]}}}'
          f' {blank}'
      )
    filled = [c if c is not None else _EMPTY_2 for c in cells]
    out.append(f'        {spec.label} & ' + ' & '.join(filled) + r' \\')

  def span(text: str) -> str:
    return f'\\multicolumn{{2}}{{c}}{{{text}}}'

  def var_cells(col: str) -> List[str]:
    cells: List[str] = []
    for r in rows:
      v = _get_float(r, col, math.nan) or 0.0
      cells.append(
          span(f'{_pct(math.sqrt(v)):.3f}\\%' if is_hrv else f'{v:.2f}')
      )
    return cells

  out.append(r'        \midrule')
  out.append(f'        \\textbf{{Variance Components}} {blank}')
  if is_hrv:
    res_label = r'\quad Residual SD (proportional) [\%]'
    int_label = r'\quad Intercept SD (proportional) [\%]'
  else:
    res_label = r'\quad Residual Var (\(\sigma^2_{\varepsilon}\))'
    int_label = r'\quad Intercept Var (\(\sigma^2_{\alpha}\) user)'
  out.append(
      f'        {res_label} & '
      + ' & '.join(var_cells('residual_noise_var'))
      + r' \\'
  )
  out.append(
      f'        {int_label} & '
      + ' & '.join(var_cells('random_intercept_var'))
      + r' \\'
  )

  if include_fit_diagnostics:
    icc = [span(f'{_get_float(r, "ICC", math.nan) or 0.0:.3f}') for r in rows]
    out.append(r'        \quad Adjusted ICC & ' + ' & '.join(icc) + r' \\')
    out.append(f'        \\midrule \\textbf{{Model Fit Diagnostics}} {blank}')
    rmse_cells = []
    for r in rows:
      rmse = _get_float(r, 'rmse', math.nan) or 0.0
      rmse_cells.append(
          span(f'{_pct(rmse):.1f}\\%' if is_hrv else f'{rmse:.3f}')
      )
    rmse_unit = r'[\%]' if is_hrv else r'[\text{bpm}]'
    out.append(
        f'        \\quad RMSE {rmse_unit} & ' + ' & '.join(rmse_cells) + r' \\'
    )
    criteria = [_fit_criteria(r, log_likelihood_is_negated) for r in rows]
    out.append(
        r'        \quad BIC (ML) & '
        + ' & '.join(
            span(_fmt_criterion(bic) or '--') for _, _, bic in criteria
        )
        + r' \\'
    )
    out.append(
        r'        \quad AIC (ML) & '
        + ' & '.join(
            span(_fmt_criterion(aic) or '--') for _, aic, _ in criteria
        )
        + r' \\'
    )
    out.append(
        r'        \quad Log-Likelihood (ML) & '
        + ' & '.join(
            span(_fmt_criterion(llf) or '--') for llf, _, _ in criteria
        )
        + r' \\'
    )
    r2 = []
    for r in rows:
      m_r2 = (_get_float(r, 'marginal_R2', math.nan) or 0.0) * 100.0
      c_r2 = (_get_float(r, 'conditional_R2', math.nan) or 0.0) * 100.0
      r2.append(span(f'{m_r2:.3f} / {c_r2:.3f}'))
    out.append(
        r'        \quad Marginal \(R^2\) / Conditional \(R^2\) [\%] & '
        + ' & '.join(r2)
        + r' \\'
    )

  if standardised:
    intro = (
        'Standardised parameter estimates across all progressive hierarchical'
        ' stages.'
    )
    est_sentence = (
        r'\emph{Std. \(\beta\)} refers to standardised fixed-effects'
        r' coefficients.'
    )
  else:
    intro = (
        'Unstandardised parameter estimates across all progressive hierarchical'
        ' stages.'
    )
    est_sentence = (
        r'\emph{Est.} denotes unstandardised coefficients (latitude terms'
        r' \(\phi\) per degree and \(\phi^2\) per degree squared).'
    )
  notes = (
      r'        \item \textbf{Notes:} '
      + intro
      + r' Fixed-effects notation defined as: \(a\), age; \(s\), sex; \(h\), '
      r'seasonal harmonics; \(\phi\), latitude; \(\lambda\), longitude; \(T\), '
      r'temperature. Interaction terms are denoted by (\(\cdot\)). '
      + est_sentence
      + ' Estimates are '
      + _PARAM_UNIT_SENTENCE[metric]
      + r'. \textbf{Bold values indicate coefficients that are NOT'
      r' statistically '
      r'significant (\(p \ge 0.05\), 95\% CI includes zero).} Empty cells '
      r'indicate variables not structurally introduced until later'
      r' hierarchical '
      r'stages. Indented items indicate explicit parameter metrics nested'
      r' within '
      r'their respective structural grouping.'
  )
  out.extend([
      r'        \bottomrule',
      r'    \end{tabular}',
      r'    \begin{tablenotes}',
      r'        \tiny',
      notes,
      r'    \end{tablenotes}',
      r'    \end{threeparttable}',
      r'\end{sidewaystable}',
  ])
  latex = '\n'.join(out)
  _write_tex(latex, out_dir, label)
  return latex


