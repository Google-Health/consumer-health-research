def _ensure_ols_features(df: pd.DataFrame) -> pd.DataFrame:
  """Returns a frame with ``OLS_FEATURE_COLUMNS``, deriving them if absent.

  Derivation: ``abs_lat_e7 = |lat_e7|``; every continuous predictor is
  centred and scaled by 2 SD over all rows of ``df``; month harmonics are
  ``sin/cos(2*pi*month/12)`` and ``.../6`` from ``activity_period``.

  Args:
    df: User-month frame with either the OLS feature or raw columns.

  Returns:
    Frame restricted to ``OLS_FEATURE_COLUMNS``.

  Raises:
    KeyError: if neither the feature nor the raw columns are present.
  """
  if all(c in df.columns for c in OLS_FEATURE_COLUMNS):
    return df.loc[:, list(OLS_FEATURE_COLUMNS)]
  missing = [c for c in OLS_RAW_COLUMNS if c not in df.columns]
  if missing:
    raise KeyError(
        f'Need either {OLS_FEATURE_COLUMNS} or the raw columns'
        f' {OLS_RAW_COLUMNS}; missing raw columns: {missing}'
    )
  work = pd.DataFrame(index=df.index)
  raw = {
      'lat_e7': df['lat_e7'].astype(float),
      'abs_lat_e7': df['lat_e7'].abs().astype(float),
  }
  for t in OLS_TEMP_VARS:
    raw[t] = df[t].astype(float)
  for col, series in raw.items():
    work[f'{col}_c'] = (series - series.mean()) / (2.0 * series.std())
  month = pd.to_datetime(df['activity_period']).dt.month
  work['month_sin'] = np.sin(2 * np.pi * month / 12)
  work['month_cos'] = np.cos(2 * np.pi * month / 12)
  work['month_sin_2'] = np.sin(2 * np.pi * month / 6)
  work['month_cos_2'] = np.cos(2 * np.pi * month / 6)
  return work


def fit_ols_temperature_params(df: pd.DataFrame) -> pd.DataFrame:
  """Fits the three OLS temperature-residualisation regressions.

  For ``temp_var`` in ``avg_temp_max``, ``avg_temp_min``, ``avg_temp_mean``
  fits ``{temp_var}_c ~ abs_lat_e7_c + (month_sin + month_cos + month_sin_2 +
  month_cos_2) * lat_e7_c`` by OLS on the user-month rows, i.e. each
  temperature variable is regressed on absolute latitude and the latitude x
  season harmonics. The residuals of these fits are the temperature
  predictors of the LME models; this function reports the fitted parameters.

  Args:
    df: User-month frame. Either already feature-engineered with
      ``OLS_FEATURE_COLUMNS`` (``abs_lat_e7_c``, ``lat_e7_c``,
      ``avg_temp_{max,min,mean}_c``, ``month_{sin,cos}``, ``month_{sin,cos}_2``)
      or the raw columns ``lat_e7``, ``activity_period``, ``avg_temp_max``,
      ``avg_temp_min``, ``avg_temp_mean`` of the clean user-month cohort frame
      (see ``cohort_io.load_cohort``), which are then centred and scaled by 2 SD
      over all rows of ``df``.

  Returns:
    Tidy frame with columns ``temp_var`` ('avg_temp_max' | 'avg_temp_min' |
    'avg_temp_mean'), ``term`` (patsy name, e.g. 'month_sin:lat_e7_c'),
    ``coef``, ``ci_low``, ``ci_high`` (95%), ``r2`` (model R^2, repeated per
    row). Save it as ``data_dir/results/{metric}/ols_temperature_params.csv``
    (see :func:`write_ols_temperature_params`).
  """
  work = _ensure_ols_features(df)
  records: List[Dict[str, Any]] = []
  for temp_var in OLS_TEMP_VARS:
    formula = OLS_FORMULA_TEMPLATE.format(temp_var=temp_var)
    res = smf.ols(formula, data=work).fit()
    conf = res.conf_int()
    r2 = float(res.rsquared)
    for term in list(res.params.index):
      records.append({
          'temp_var': temp_var,
          'term': str(term),
          'coef': float(res.params[term]),
          'ci_low': float(conf.loc[term, 0]),
          'ci_high': float(conf.loc[term, 1]),
          'r2': r2,
      })
  return pd.DataFrame(
      records, columns=['temp_var', 'term', 'coef', 'ci_low', 'ci_high', 'r2']
  )


