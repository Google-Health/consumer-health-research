def _label_to_stem(label: str) -> str:
  """``tab:results_rhr`` -> ``results_rhr`` (colons are not file-name safe)."""
  stem = label[4:] if label.startswith('tab:') else label
  return stem.replace(':', '_')


def _write_tex(latex: str, out_dir: Optional[str], label: str) -> None:
  """Writes ``latex`` to ``out_dir/{stem}.tex`` via file_io (no-op if None)."""
  if out_dir is None:
    return
  path = os.path.join(out_dir, f'{_label_to_stem(label)}.tex')
  with fio.open_file(path, 'w') as f:
    f.write(latex)


# Inline preview of a LaTeX table (notebook display) ---------------------------

_RULE_RE = re.compile(
    r'\\(toprule|midrule|bottomrule|hline|addlinespace|cmidrule)(\[[^\]]*\])?'
    r'(\([^)]*\))?(\{[^}]*\})?'
)
_MULTICOLUMN_RE = re.compile(r'\\multicolumn\{(\d+)\}\{[^}]*\}\{')
# A ``tabular`` opened and closed on one line is a stacked cell, not a table.
_NESTED_TABULAR_RE = re.compile(
    r'\\begin\{tabular\}(?:\[[^\]\n]*\])?'
    r'\{(?:[^{}\n]|\{[^{}\n]*\})*\}([^\n]*?)\\end\{tabular\}'
)
_WRAPPER_RE = re.compile(
    r'\\(textbf|textit|emph|text|mathrm|mathit|mathbf|textsuperscript|mbox|'
    r'textsubscript|scriptsize|footnotesize|small|tiny|normalsize)\s*\{'
)
_SIMPLE_CMD_RE = re.compile(r'\\(?:[a-zA-Z]+)\*?')
_INLINE_MATH_RE = re.compile(r'\\\(|\\\)|\$')
_SPACES_RE = re.compile(r'\s+')
# Math commands that appear in the row labels, mapped to Unicode for the
# preview (anything else is dropped by _SIMPLE_CMD_RE).
_MATH_SYMBOLS: Dict[str, str] = {
    'alpha': 'α',
    'beta': 'β',
    'phi': 'φ',
    'lambda': 'λ',
    'sigma': 'σ',
    'mu': 'μ',
    'tau': 'τ',
    'cdot': '·',
    'times': '×',
    'pm': '±',
    'ge': '≥',
    'le': '≤',
    'max': 'max',
    'min': 'min',
    'sin': 'sin',
    'cos': 'cos',
    'exp': 'exp',
    'log': 'log',
}
_MATH_SYMBOL_RE = re.compile(
    r'\\('
    + '|'.join(sorted(_MATH_SYMBOLS, key=len, reverse=True))
    + r')(?![a-zA-Z])'
)


def _strip_balanced(text: str, start: int) -> Tuple[str, int]:
  """Returns the content of the ``{...}`` group starting at ``start`` and the end index."""
  depth = 0
  for i in range(start, len(text)):
    if text[i] == '{':
      depth += 1
    elif text[i] == '}':
      depth -= 1
      if depth == 0:
        return text[start + 1 : i], i + 1
  return text[start + 1 :], len(text)


def _unwrap_commands(text: str, pattern: 're.Pattern[str]') -> str:
  r"""Replaces ``\cmd{arg}`` by ``arg`` for every command matched by ``pattern``."""
  while True:
    m = pattern.search(text)
    if m is None:
      return text
    inner, end = _strip_balanced(text, m.end() - 1)
    text = text[: m.start()] + inner + text[end:]


def latex_cell_to_text(cell: str) -> str:
  r"""Best-effort plain-text rendering of one LaTeX table cell.

  Unwraps ``\textbf{}`` / ``\textit{}`` / ``\text{}`` and friends, drops inline
  math delimiters, maps Greek letters / operators and ``\%``, ``\&``, ``~``,
  ``\,`` to their characters and removes any remaining command
  (``\scriptsize`` ...). Super/subscripts are kept as ``^``/``_`` source.

  Args:
    cell: LaTeX source of one cell (or caption / note).

  Returns:
    Plain text with collapsed whitespace.
  """
  text = _unwrap_commands(cell, _WRAPPER_RE)
  text = _INLINE_MATH_RE.sub('', text)
  text = _MATH_SYMBOL_RE.sub(lambda m: _MATH_SYMBOLS[m.group(1)], text)
  text = (
      text.replace(r'\%', '%')
      .replace(r'\&', '&')
      .replace(r'\_', '_')
      .replace(r'\,', ' ')
      .replace('~', ' ')
      .replace(r'\\', ' ')
  )
  text = _SIMPLE_CMD_RE.sub('', text)
  text = text.replace('{', '').replace('}', '')
  return _SPACES_RE.sub(' ', text).strip()


def _split_cells(row: str) -> List[str]:
  r"""Splits a ``tabular`` row on unescaped ``&`` and expands ``\multicolumn``."""
  cells: List[str] = []
  for raw in re.split(r'(?<!\\)&', row):
    m = _MULTICOLUMN_RE.match(raw.strip())
    if m:
      inner, _ = _strip_balanced(raw.strip(), m.end() - 1)
      cells.append(latex_cell_to_text(inner))
      cells.extend([''] * (int(m.group(1)) - 1))
    else:
      cells.append(latex_cell_to_text(raw))
  return cells


def table_preview(latex: str) -> pd.DataFrame:
  r"""Renders the ``tabular`` body of a generated table as a DataFrame.

  Used by the notebooks to show the generated tables inline; the LaTeX string
  is the source of truth. The first row of the ``tabular``/``tabularx``
  becomes the header, every later row (``\\``-terminated, rules and
  ``\multicolumn`` expanded) becomes a record. Formatting commands
  are stripped with :func:`latex_cell_to_text`, so this is a readable preview,
  not a typographic rendering (italics marking non-significant terms, for
  example, are lost). Table notes and captions are exposed through
  ``DataFrame.attrs['caption']`` / ``attrs['notes']`` when present.

  Args:
    latex: Output of any ``*_table`` function of this module.

  Returns:
    DataFrame of strings; empty if no ``tabular`` environment is found.
  """
  # The column spec follows ``\begin{...}`` on the same line in every generator
  # (``tabularx`` has two arguments and nested braces, so it is not parsed).
  latex = _NESTED_TABULAR_RE.sub(
      lambda m: m.group(1).replace(r'\\', ' '), latex
  )
  m = re.search(
      r'\\begin\{(tabular|tabularx|longtable)\}[^\n]*\n(.*?)\\end\{\1\}',
      latex,
      re.S,
  )
  if m is None:
    return pd.DataFrame()
  body = _RULE_RE.sub('', m.group(2))
  rows = [r.strip() for r in re.split(r'\\\\', body)]
  rows = [r for r in rows if r and re.search(r'[^\s%]', r)]
  if not rows:
    return pd.DataFrame()
  header = _split_cells(rows[0])
  width = len(header)
  records = []
  for r in rows[1:]:
    cells = _split_cells(r)
    cells = (cells + [''] * width)[:width]
    records.append(cells)
  header = [h if h else f'col{i}' for i, h in enumerate(header)]
  df = pd.DataFrame(records, columns=header)
  cap = re.search(r'\\caption\{', latex)
  if cap:
    df.attrs['caption'] = latex_cell_to_text(
        _strip_balanced(latex, cap.end() - 1)[0]
    )
  notes = re.search(r'\\item\s*(.*?)\\end\{tablenotes\}', latex, re.S)
  if notes:
    df.attrs['notes'] = latex_cell_to_text(notes.group(1))
  return df


def _is_hrv(metric: str) -> bool:
  if metric not in METRICS:
    raise ValueError(f'metric must be one of {METRICS}, got {metric!r}')
  return metric == 'hrv'


def _get_float(
    row: Row, col: str, default: Optional[float] = None
) -> Optional[float]:
  """Returns ``row[col]`` as float, or ``default`` if absent / NaN / empty."""
  if col not in row:
    return default
  val = row[col]
  if val is None:
    return default
  if isinstance(val, str):
    return float(val) if val.strip() else default
  if pd.isna(val):
    return default
  return float(val)


def _float_or_nan(row: Row, col: str) -> float:
  """``row[col]`` as float; NaN if absent / NaN / empty."""
  value = _get_float(row, col, math.nan)
  return math.nan if value is None else value


def _coef_ci(
    row: Row, kind: str, var: str
) -> Optional[Tuple[float, float, float]]:
  """(beta, ci_low, ci_high) for ``beta_{kind}_{var}``; None if beta missing.

  Args:
    row: One results-CSV row (a fitted model) as a column -> value dict.
    kind: Coefficient scale, ``'std'`` (standardised) or ``'raw'``.
    var: Fixed-effect term name, e.g. ``'month_sin'`` or ``'age_c:gender_n'``.

  Returns:
    ``(beta, ci_low, ci_high)`` read from ``beta_{kind}_{var}``,
    ``ci_low_{kind}_{var}`` and ``ci_high_{kind}_{var}`` (NaN bounds when the
    CI columns are absent or empty, e.g. fits without a Hessian), or None
    when the beta column is absent or NaN.
  """
  beta = _get_float(row, f'beta_{kind}_{var}')
  if beta is None:
    return None
  lo = _float_or_nan(row, f'ci_low_{kind}_{var}')
  hi = _float_or_nan(row, f'ci_high_{kind}_{var}')
  return beta, lo, hi


def _fmt_ci(lo: float, hi: float, fmt: str = '{:.2f}', suffix: str = '') -> str:
  """``[lo, hi]`` with ``--`` for NaN bounds."""

  def one(v: float) -> str:
    return '--' if math.isnan(v) else fmt.format(v) + suffix

  return f'[{one(lo)}, {one(hi)}]'


def _pct(log_value: float) -> float:
  """HRV back-transform: log-scale coefficient -> percentage change."""
  return (math.exp(log_value) - 1.0) * 100.0


def _month_name(t_peak: float) -> str:
  """1-indexed peak month (fractional) -> 3-letter month name."""
  idx = (int(round(t_peak)) - 1) % 12
  return MONTH_NAMES[idx]


def _amplitude_phase(
    b_sin: float, b_cos: float, period: int
) -> Tuple[float, str]:
  """Combines a (sin, cos) harmonic pair into amplitude and peak phase.

  Phase is ``atan2(sin, cos) * period / 2pi`` wrapped to ``[0, period)``;
  shown as a month name for the annual harmonic and as ``X.Xm`` otherwise.

  Args:
    b_sin: Coefficient of the ``sin(2*pi*t/period)`` term.
    b_cos: Coefficient of the ``cos(2*pi*t/period)`` term.
    period: Harmonic period in months (12 = annual, 6 = semi-annual).

  Returns:
    ``(amplitude, phase)`` where ``amplitude = sqrt(b_sin^2 + b_cos^2)`` and
    ``phase`` is the 3-letter peak month (``period == 12``) or the peak time
    in months formatted as ``'X.Xm'``.
  """
  amp = math.sqrt(b_sin**2 + b_cos**2)
  t_peak = math.atan2(b_sin, b_cos) * period / (2.0 * math.pi)
  if t_peak < 0:
    t_peak += period
  phase = _month_name(t_peak) if period == 12 else f'{t_peak:.1f}m'
  return amp, phase


def _fit_criteria(
    row: Row, log_likelihood_is_negated: bool
) -> Tuple[float, float, float]:
  """Returns ``(llf, AIC, BIC)`` of a results row.

  Args:
    row: One results-CSV row with ``log_likelihood``, ``AIC`` and ``BIC``.
    log_likelihood_is_negated: True if ``log_likelihood`` stores ``-llf``
      (results CSVs of earlier versions).

  Returns:
    ``(llf, AIC, BIC)`` as floats; NaN where a column is missing or empty
    (``_fmt_criterion`` renders NaN as an empty cell).
  """
  raw_log_likelihood = _float_or_nan(row, 'log_likelihood')
  aic = _float_or_nan(row, 'AIC')
  bic = _float_or_nan(row, 'BIC')
  log_likelihood = (
      -raw_log_likelihood if log_likelihood_is_negated else raw_log_likelihood
  )
  return log_likelihood, aic, bic


def _fmt_criterion(value: float, thousands: bool = False) -> Optional[str]:
  """Formats a fit criterion as a rounded integer; None if it is NaN.

  Args:
    value: llf, AIC or BIC.
    thousands: Insert thousands separators (``1,234``).

  Returns:
    The rounded integer as a string, or None when ``value`` is NaN so that the
    caller can emit its empty-cell placeholder.
  """
  if math.isnan(value):
    return None
  return f'{value:,.0f}' if thousands else f'{value:.0f}'


