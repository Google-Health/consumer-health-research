"""LaTeX tables for the seasonal mixed-effects models of RHR and HRV.

Builds every data-driven table of the analysis from the result files of a
run (``{results_dir}/{run_tag}/``): the staged BIC model competition of linear
mixed-effects (LME) models with a per-user random intercept, the fixed-effect
estimates of the stage winners, the OLS temperature residualisation and the
cohort demographics. Each public ``*_table`` function is a pure function
``(dataframe, params) -> latex_str`` and optionally writes
``out_dir/{label-without-'tab:'}.tex`` via ``file_io``.

Table label -> function
-----------------------
* ``tab:results_{rhr,hrv}`` (main results, 5 stage-winner columns)
  -> :func:`results_table`.
* ``tab:results_{rhr,hrv}_full_grid`` (fit diagnostics of every candidate
  model of the competition) -> :func:`candidate_comparison_table`.
* ``tab:supp_results_{rhr,hrv}_unstandardised`` / ``_standardised`` (full
  11-column parameter tables of the stage winners)
  -> :func:`unstandardised_parameter_table` /
  :func:`standardised_parameter_table`.
* ``tab:{rhr,hrv}_ols_params`` (OLS temperature residualisation parameters)
  -> :func:`ols_params_table` fed by :func:`fit_ols_temperature_params`.
* ``tab:rhr_demographics_thinned`` / ``tab:hrv_demographics_original``
  (participant demographics by latitude band) -> :func:`demographics_table`
  (input: ``seasonality_lib.get_user_summary``).
* The model-specification tables are not generated by this module.

Stage numbering: the tables report five stages (1 demographics, 2 season,
3 spatial geography, 4 temperature, 5 joint) while the fitting pipeline has
six; see ``infer_stage_winners`` / ``STAGE_MODEL_PREFIXES`` for the mapping.

Input: the per-run LME summary CSV
----------------------------------
``{results_dir}/{run_tag}/lme-models-results-{metric}.csv`` with one row per
fitted model, written by ``seasonality_lib.extract_model_stats``. Columns used
here: ``model``, ``formula``, ``random_intercept_var``, ``residual_noise_var``,
``rmse``, ``AIC``, ``BIC``, ``ICC``, ``log_likelihood``, ``marginal_R2``,
``conditional_R2`` and, for every fixed-effect term ``X``, ``beta_std_X``,
``ci_low_std_X``, ``ci_high_std_X``, ``beta_raw_X``, ``ci_low_raw_X``,
``ci_high_raw_X`` (NaN when the term is not in the model).

Sign convention of ``log_likelihood``: ``extract_model_stats`` stores
``result.llf`` (true sign, like ``AIC``/``BIC``). Results CSVs written by
earlier versions hold ``-llf``; pass ``log_likelihood_is_negated=True`` to the
table functions for those.
"""

