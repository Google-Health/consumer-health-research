def ols_params_table(
    ols_params_df: pd.DataFrame,
    metric: str,
    caption: Optional[str] = None,
    label: Optional[str] = None,
    out_dir: Optional[str] = None,
) -> str:
  """OLS temperature residualisation parameters ``tab:{metric}_ols_params``.

  Rows: intercept, |latitude| slope, signed latitude slope, the four month
  harmonics and their latitude interactions, then the model R^2; columns:
  ``T_max``, ``T_min``, ``T_mean`` as ``coef [ci_low, ci_high]`` with 4
  decimals.

  Args:
    ols_params_df: Output of :func:`fit_ols_temperature_params` /
      :func:`load_ols_temperature_params`: columns ``temp_var``, ``term``,
      ``coef``, ``ci_low``, ``ci_high``, ``r2``. ``temp_var`` may carry the
      ``_c`` suffix.
    metric: 'rhr' or 'hrv' (caption / label only).
    caption: Caption text; a default is provided.
    label: LaTeX label; default ``tab:{metric}_ols_params``.
    out_dir: If given, writes ``{out_dir}/{metric}_ols_params.tex``.

  Returns:
    The complete ``table`` LaTeX block.
  """
  _is_hrv(metric)
  caption = caption or (
      'OLS temperature residualisation regression parameters for the '
      f'{metric.upper()} cohort.'
  )
  label = label or f'tab:{metric}_ols_params'

  lookup: Dict[Tuple[str, str], Tuple[float, float, float]] = {}
  r2_by_var: Dict[str, float] = {}
  for rec in ols_params_df.to_dict('records'):
    temp_var = re.sub(r'_c$', '', str(rec['temp_var']))
    term = str(rec['term'])
    lookup[(temp_var, term)] = (
        float(rec['coef']),
        float(rec['ci_low']),
        float(rec['ci_high']),
    )
    r2 = rec.get('r2')
    if temp_var not in r2_by_var and r2 is not None and not pd.isna(r2):
      r2_by_var[temp_var] = float(r2)

  header = ' & '.join(
      f'\\textbf{{{OLS_TEMP_HEADERS[t]} [95\\% CI]}}' for t in OLS_TEMP_VARS
  )
  out = [
      r'\begin{table}[ht]',
      r'\centering',
      r'\setlength{\tabcolsep}{3pt}',
      r'\scriptsize',
      f'\\caption{{\\textbf{{{caption}}}}}',
      f'\\label{{{label}}}',
      r'\begin{tabular}{lccc}',
      r'\toprule',
      f'\\textbf{{Parameter}} & {header} \\\\',
      r'\midrule',
  ]
  for term, row_label in OLS_TERM_LABELS:
    cells: List[str] = []
    for temp_var in OLS_TEMP_VARS:
      est = lookup.get((temp_var, term))
      if est is None:
        cells.append('--')
      else:
        coef, lo, hi = est
        cells.append(f'\\({coef:.4f}\\text{{ }} [{lo:.4f}, {hi:.4f}]\\)')
    out.append(f'{row_label} & ' + ' & '.join(cells) + r' \\')
  r2_cells = [
      f'\\({r2_by_var[t]:.4f}\\)' if t in r2_by_var else '--'
      for t in OLS_TEMP_VARS
  ]
  out.extend([
      r'\midrule',
      r'Model \(R^2\) & ' + ' & '.join(r2_cells) + r' \\',
      r'\bottomrule',
      r'\end{tabular}',
      r'\end{table}',
  ])
  latex = '\n'.join(out)
  _write_tex(latex, out_dir, label)
  return latex


