def generate_all_tables(
    data_dir: str,
    out_dir: Optional[str] = None,
    metrics: Sequence[str] = METRICS,
    *,
    results_subdirs: Mapping[str, str],
    winners: Optional[Dict[str, Dict[int, str]]] = None,
    log_likelihood_is_negated: bool = False,
) -> Dict[str, str]:
  """Builds every table for the given metrics.

  Reads ``data_dir/results/{run_tag}/lme-models-results-{metric}.csv`` and, if
  present, ``.../ols_temperature_params.csv`` (produced by
  :func:`fit_ols_temperature_params` + :func:`write_ols_temperature_params`).
  The demographics tables are NOT built here because they need the clean
  user-month cohort frame (see ``cohort_io.load_cohort``; for RHR the thinned
  cohort); call
  ``demographics_table(seasonality_lib.get_user_summary(df, target_col),
  metric)`` from the caller instead.

  Args:
    data_dir: Project data root.
    out_dir: If given, each table is written to ``{out_dir}/{stem}.tex`` where
      ``stem`` is the label without the ``tab:`` prefix.
    metrics: Subset of ``('rhr', 'hrv')``.
    results_subdirs: metric -> run tag, i.e. the sub-directory under
      ``results/`` written by notebook 02 (e.g. ``{'rhr': 'rhr_rerun'}``);
      required for every metric in ``metrics``.
    winners: metric -> stage winners; metrics missing from the mapping (or None)
      have their winners inferred from the run's results CSV with
      ``infer_stage_winners``.
    log_likelihood_is_negated: See module docstring.

  Returns:
    label -> LaTeX string, e.g. ``{'tab:results_rhr': ..., ...}``.

  Raises:
    KeyError: a metric in ``metrics`` has no entry in ``results_subdirs``.
  """
  missing = [m for m in metrics if m not in results_subdirs]
  if missing:
    raise KeyError(f'results_subdirs lacks the run tag(s) for {missing}')
  winners = winners or {}
  tables: Dict[str, str] = {}
  for metric in metrics:
    subdir = results_subdirs[metric]
    results_df = load_model_results(data_dir, metric, subdir)
    w = winners.get(metric) or infer_stage_winners(results_df)
    neg = log_likelihood_is_negated
    tables[f'tab:results_{metric}'] = results_table(
        results_df,
        metric,
        winners=w,
        log_likelihood_is_negated=neg,
        out_dir=out_dir,
    )
    tables[f'tab:results_{metric}_full_grid'] = candidate_comparison_table(
        results_df,
        metric,
        winners=w,
        log_likelihood_is_negated=neg,
        out_dir=out_dir,
    )
    tables[f'tab:supp_results_{metric}_unstandardised'] = (
        unstandardised_parameter_table(
            results_df,
            metric,
            winners=w,
            log_likelihood_is_negated=neg,
            out_dir=out_dir,
        )
    )
    tables[f'tab:supp_results_{metric}_standardised'] = (
        standardised_parameter_table(
            results_df,
            metric,
            winners=w,
            log_likelihood_is_negated=neg,
            out_dir=out_dir,
        )
    )
    ols_path = _ols_params_path(data_dir, metric, subdir)
    if fio.file_exists(ols_path):
      ols_df = load_ols_temperature_params(data_dir, metric, subdir)
      tables[f'tab:{metric}_ols_params'] = ols_params_table(
          ols_df, metric, out_dir=out_dir
      )
  return tables
