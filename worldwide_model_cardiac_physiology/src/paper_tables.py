  specs.append(s(r'\quad \(\phi\) (Latitude)', 3, single='lat_e7_c'))
  specs.append(s(r'\quad \(\phi^2\)', 3, single='lat_e7_sq_c'))
  for var, lbl in _HARMONIC_LABELS:
    specs.append(
        s(f'\\quad \\(\\phi \\cdot {lbl}\\)', 3, single=f'{var}:lat_e7_c')
    )
    specs.append(
        s(f'\\quad \\(\\phi^2 \\cdot {lbl}\\)', 3, single=f'{var}:lat_e7_sq_c')
    )
